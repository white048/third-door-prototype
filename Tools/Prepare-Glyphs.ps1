$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$scriptRoot = Join-Path $projectRoot 'Assets\ThirdDoor\Scripts'
$characters = [Collections.Generic.SortedSet[int]]::new()
32..126 | ForEach-Object { [void]$characters.Add($_) }
foreach($source in Get-ChildItem -LiteralPath $scriptRoot -Recurse -Filter *.cs) {
    if($source.Name -eq 'NarrativeGlyphs.cs'){continue}
    $body = [IO.File]::ReadAllText($source.FullName)
    foreach($character in $body.ToCharArray()) {
        $point = [int]$character
        if($point -ge 127 -and ![char]::IsSurrogate($character) -and ![char]::IsControl($character)){[void]$characters.Add($point)}
    }
}
$escaped = ($characters | ForEach-Object { '\u{0:x4}' -f $_ }) -join ''
$content = "// Generated by Tools/Prepare-Glyphs.ps1 from the game's text; both languages are included.`npublic static class NarrativeGlyphs`n{`n    public const string All = `"$escaped`";`n}`n"
[IO.File]::WriteAllText((Join-Path $scriptRoot 'NarrativeGlyphs.cs'),$content)
Write-Output "Prepared $($characters.Count) exhibition glyphs."
